import axios from 'axios'
import { clearAuthSession } from '../utils/session'

const BASE = import.meta.env.VITE_API_URL

const api = axios.create({ baseURL: BASE })

// ── Attach access token to every request ─────────────────────────────────────
api.interceptors.request.use((config) => {
  const token = localStorage.getItem('access_token')
  if (token) config.headers.Authorization = `Bearer ${token}`
  return config
})

// ── Auto-refresh access token on 401 ─────────────────────────────────────────
let isRefreshing   = false
let failedQueue    = []

const processQueue = (error, token = null) => {
  failedQueue.forEach(({ resolve, reject }) => {
    if (error) reject(error)
    else resolve(token)
  })
  failedQueue = []
}

api.interceptors.response.use(
  (res) => res,
  async (error) => {
    const original = error.config

    // Only attempt refresh on 401, and only once per request
    if (error.response?.status === 401 && !original._retry) {
      const refreshToken = localStorage.getItem('refresh_token')

      // Don't logout on SSE 401 — SSE reconnects automatically
      if (original.url?.includes('/notifications/sse')) {
        return Promise.reject(error)
      }

      // No refresh token — logout immediately
      if (!refreshToken) {
        clearAuthSession()
        window.location.href = '/login'
        return Promise.reject(error)
      }

      if (isRefreshing) {
        // Queue this request until refresh completes
        return new Promise((resolve, reject) => {
          failedQueue.push({ resolve, reject })
        }).then((token) => {
          original.headers.Authorization = `Bearer ${token}`
          return api(original)
        }).catch((err) => Promise.reject(err))
      }

      original._retry  = true
      isRefreshing     = true

      try {
        const { data } = await axios.post(
          `${BASE}/api/auth/token/refresh/`,
          { refresh: refreshToken }
        )

        const newAccess = data.access
        localStorage.setItem('access_token', newAccess)
        api.defaults.headers.common['Authorization'] = `Bearer ${newAccess}`

        processQueue(null, newAccess)

        original.headers.Authorization = `Bearer ${newAccess}`
        return api(original)
      } catch (refreshError) {
        processQueue(refreshError, null)
        // Only a real server-rejected refresh (the refresh token itself is
        // invalid/expired/blacklisted, i.e. refreshError.response exists)
        // should force a logout. A network error/timeout mid-refresh has
        // no .response — that's connectivity, not an invalid session, so
        // keep the stored tokens/user and let the caller (offline queue,
        // useAuth, etc.) treat this as a failed request and retry later.
        if (refreshError.response) {
          clearAuthSession()
          window.location.href = '/login'
        }
        return Promise.reject(refreshError)
      } finally {
        isRefreshing = false
      }
    }

    return Promise.reject(error)
  }
)

/**
 * Admin-only: change an existing account's role (Staff <-> Enforcer).
 * The new ID number is always generated by the server; none is sent.
 * `expectedRole` is the role the admin saw, so the server can refuse a stale request.
 */
export const changeUserRole = (userId, { newRole, reason, expectedRole } = {}) => {
  const payload = { new_role: newRole, reason }
  if (expectedRole !== undefined && expectedRole !== null) payload.expected_role = expectedRole
  return api.post(`/api/auth/users/${userId}/change-role/`, payload)
}

export default api