import jsPDF from 'jspdf'
import autoTable from 'jspdf-autotable'
import {
  SUMMARY_DEFS, appliedFilterPairs, cellText, fmtDateTime, summaryText,
} from './reportsConfig'

/**
 * Reusable client-side PDF renderer for every report.
 *
 *   buildReportPdf(payload, { header })  →  jsPDF document
 *
 * `payload` is the exact API response ({meta, summary, rows}) — the PDF is
 * drawn from the same columns/rows/notes the screen shows, so the two can
 * never disagree. `header` is an optional slot for a custom letterhead:
 *   header(doc, { margin, pageWidth }) → y position where content starts.
 *
 * Palette is black/gray only (prints cleanly in greyscale).
 * "Page X of Y" is written in a second pass, after every page exists — it
 * cannot be correct inside autoTable's per-page hook.
 */
const INK = [17, 17, 17]
const GREY = [90, 90, 90]
const LIGHT = [235, 235, 235]
const MARGIN = 36

function defaultHeader(doc, { margin, pageWidth }) {
  doc.setFont('helvetica', 'bold'); doc.setFontSize(14); doc.setTextColor(...INK)
  doc.text('Traffic Management and Enforcement Office', margin, 40)
  doc.setFont('helvetica', 'normal'); doc.setFontSize(10); doc.setTextColor(...GREY)
  doc.text('Lucena City', margin, 54)
  doc.setDrawColor(...INK); doc.setLineWidth(1)
  doc.line(margin, 62, pageWidth - margin, 62)
  return 62
}

export function buildReportPdf(payload, { header = defaultHeader } = {}) {
  const { meta, summary, rows } = payload
  const doc = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'a4' })
  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()
  const usable = pageWidth - MARGIN * 2
  const ensure = (y, need) => {
    if (y + need > pageHeight - 40) { doc.addPage(); return MARGIN }
    return y
  }
  const paragraph = (text, y, { size = 9, color = GREY, bold = false } = {}) => {
    doc.setFont('helvetica', bold ? 'bold' : 'normal'); doc.setFontSize(size); doc.setTextColor(...color)
    const lines = doc.splitTextToSize(text, usable)
    y = ensure(y, lines.length * (size + 3))
    doc.text(lines, MARGIN, y)
    return y + lines.length * (size + 3)
  }

  let y = header(doc, { margin: MARGIN, pageWidth }) + 22

  // Title + generated metadata
  doc.setFont('helvetica', 'bold'); doc.setFontSize(16); doc.setTextColor(...INK)
  doc.text(meta.title, MARGIN, y)
  y += 16
  y = paragraph(`Generated: ${fmtDateTime(meta.generated_at)}     Generated By: ${meta.generated_by || '—'}`, y)
  y = paragraph(`Scope: ${meta.scope}`, y)

  // Applied filters — exactly what the server reports it applied.
  const pairs = appliedFilterPairs(meta.filters_applied)
  y = paragraph(`Applied filters: ${pairs.length ? pairs.map(([k, v]) => `${k}: ${v}`).join('   |   ') : 'None (all records)'}`, y, { color: INK })
  y += 6

  // Summary
  const defs = SUMMARY_DEFS[meta.report] || []
  if (defs.length) {
    autoTable(doc, {
      startY: y, margin: { left: MARGIN, right: MARGIN }, theme: 'plain',
      head: [defs.map(d => d[0])],
      body: [defs.map(d => summaryText(d, summary, { pdf: true }))],
      styles: { font: 'helvetica', fontSize: 10, cellPadding: 5, textColor: INK, lineColor: LIGHT, lineWidth: 0.5 },
      headStyles: { fontStyle: 'bold', fontSize: 8, textColor: GREY },
      bodyStyles: { fontStyle: 'bold' },
    })
    y = doc.lastAutoTable.finalY + 14
  }

  // Table
  const columns = meta.columns
  if (rows.length) {
    autoTable(doc, {
      startY: y, margin: { left: MARGIN, right: MARGIN, bottom: 40 },
      head: [columns.map(c => c.label)],
      body: rows.map(r => columns.map(c => cellText(c, r, { pdf: true }))),
      styles: { font: 'helvetica', fontSize: 8.5, cellPadding: 4, textColor: INK, lineColor: [200, 200, 200], lineWidth: 0.4, overflow: 'linebreak' },
      headStyles: { fillColor: [40, 40, 40], textColor: 255, fontStyle: 'bold' },
      alternateRowStyles: { fillColor: [245, 245, 245] },
      columnStyles: Object.fromEntries(columns.map((c, i) => [i, { halign: c.align === 'right' ? 'right' : 'left' }])),
      showHead: 'everyPage',
    })
    y = doc.lastAutoTable.finalY + 14
  } else {
    y = paragraph('No records match the selected filters.', y, { size: 10, color: INK })
  }

  // Record count + notes
  y = paragraph(`Total records: ${rows.length}`, y, { size: 9, color: INK, bold: true })
  ;(meta.notes || []).forEach(n => { y = paragraph(`Note: ${n}`, y + 2, { size: 8 }) })
  if (payload.summary?.fines_coverage === 'partial' || rows.some(r => r.fines_coverage === 'partial')) {
    paragraph('* Partial total: some imported items have no item-level penalty and are excluded from this amount.', y + 2, { size: 8 })
  }

  // Footer pass — runs AFTER all pages exist, so "of Y" is correct.
  const total = doc.getNumberOfPages()
  for (let p = 1; p <= total; p++) {
    doc.setPage(p)
    doc.setFont('helvetica', 'normal'); doc.setFontSize(8); doc.setTextColor(...GREY)
    doc.text(`${meta.title}  —  Generated ${fmtDateTime(meta.generated_at)} by ${meta.generated_by || '—'}`, MARGIN, pageHeight - 18)
    doc.text(`Page ${p} of ${total}`, pageWidth - MARGIN, pageHeight - 18, { align: 'right' })
  }
  return doc
}

export const reportFileName = (meta) => {
  const f = meta.filters_applied || {}
  const range = f.date_from || f.date_to ? `_${f.date_from || 'start'}_to_${f.date_to || 'latest'}` : ''
  return `TMEO_${meta.report}${range}.pdf`
}