/* ── Mobile offline-report card ── */
function OfflineCard({ r, onRetry }) {
  const ss = STATUS_STYLE[r.syncStatus] || STATUS_STYLE.queued
  return (
    <div className="card" style={{ padding: '12px 14px', display: 'flex', flexDirection: 'column', gap: 6 }}>
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', gap: 8 }}>
        <div style={{ minWidth: 0 }}>
          <div style={{ fontSize: 13.5, fontWeight: 700, color: 'var(--slate-950)' }}>{r.violator_name || '—'}</div>
          {r.ovr_number && <div className="mono" style={{ fontSize: 11, color: 'var(--navy-700)', fontWeight: 700, marginTop: 1 }}>OVR: {r.ovr_number}</div>}
          <div className="mono" style={{ fontSize: 11, color: 'var(--slate-500)', marginTop: 1 }}>{r.plate_number || '—'}</div>
        </div>
        <Badge tone={ss.tone}>{ss.label}</Badge>
      </div>

      {(r.violation_names || []).length > 0 && (
        <div style={{ display: 'flex', flexWrap: 'wrap', gap: 4 }}>
          {r.violation_names.map((n, ni) => <Badge key={ni} tone="info" dot={false}>{n}</Badge>)}
        </div>
      )}

      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
        <span style={{ fontSize: 13, fontWeight: 700, color: 'var(--slate-950)' }}>
          {r.penalty_amount != null ? `₱${parseFloat(r.penalty_amount).toLocaleString('en-PH', { minimumFractionDigits: 2 })}` : '—'}
        </span>
        <span className="text-caption">
          {r.savedAt ? new Date(r.savedAt).toLocaleString('en-PH', { month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' }) : '—'}
        </span>
      </div>

      {r.location && <div className="text-caption" style={{ overflow: 'hidden', textOverflow: 'ellipsis', whiteSpace: 'nowrap' }}>📍 {r.location}</div>}

      {r.photo_dropped && r.syncStatus !== 'synced' && (
        <div className="text-caption" style={{ color: 'var(--warning-600)', fontWeight: 600 }}>
          ⚠ Photo evidence was not saved offline — this report will sync without it.
        </div>
      )}

      {r.syncStatus === 'failed' ? (
        <div style={{ display: 'flex', gap: 8, marginTop: 2 }}>
          <Button variant="secondary" size="sm" icon={RotateCw} onClick={() => onRetry(r.id)}>Retry</Button>
        </div>
      ) : r.syncStatus === 'synced' ? (
        <span style={{ fontSize: 12, color: 'var(--success-600)', fontWeight: 700 }}>✓ Done</span>
      ) : null}
    </div>
  )
}

export default function SyncData() {
  const user = JSON.parse(localStorage.getItem('user') || '{}')
  const { isMobile } = useBreakpoint()

  const {
    reports, quarantined, isOnline, syncing, lastSyncResult,
    sync: handleSync, retry: handleRetry, add,
    queuedCount, failedCount, syncedCount,
  } = useOfflineQueue()

  const [violationTypes, setViolationTypes]   = useState(getCachedVTypes)
  const [showForm, setShowForm]               = useState(false)
  const [step, setStep]                       = useState(1)
  const [form, setForm]                       = useState(EMPTY_FORM)
  const [formError, setFormError]             = useState('')
  // Offline Issuances KPI — the total count of backend violation records
  // originally created through the dedicated offline workflow
  // (client_offline_id IS NOT NULL). This comes from the role-scoped
  // /api/violations/stats/ endpoint, NEVER from the local sync queue, so
  // it stays correct even after a record has finished syncing and left
  // this device's queue entirely.
  const [offlineIssuances, setOfflineIssuances] = useState(0)

  const refreshOfflineIssuances = () => {
    api.get(API.VIOLATION_STATS)
      .then(res => setOfflineIssuances(res.data?.offline_issuances ?? 0))
      .catch(() => {})
  }

  // Refresh on mount...
  useEffect(() => {
    refreshOfflineIssuances()
  }, [])

  // ...and again whenever a sync run completes, since a successful sync
  // can turn a queued offline record into a counted Offline Issuance.
  useEffect(() => {
    if (!lastSyncResult) return
    refreshOfflineIssuances()
  }, [lastSyncResult])

  // ── cache reference data the offline form needs ─────────────────────────
  // Sync Data is the ONLY offline OVR entry point, so both datasets Save
  // Offline Report needs (violation types incl. penalties, and the vehicle
  // catalog) are refreshed here as soon as this page is open while online —
  // not lazily, e.g. only once the enforcer opens the form and reaches
  // Step 2. That way the cache is warm before connectivity is ever lost,
  // even if the enforcer never happens to use Issue OVR (which shares the
  // same 'tmeo_cached_violation_types' key) first.
  useEffect(() => {
    if (!isOnline) return
    api.get(`${API.VIOLATION_TYPES}?page_size=100`)
      .then(res => {
        const data  = res.data
        const types = Array.isArray(data) ? data : (data.results || [])
        setViolationTypes(types)
        cacheVTypes(types)
      })
      .catch(() => {})
  }, [isOnline])

  // Vehicle catalog: useVehicleCatalog() fetches (when online) and caches
  // to 'tmeo_cached_vehicle_catalog' as a side effect of being mounted —
  // calling it here (in addition to inside VehicleCatalogField, which the
  // Step 2 form also uses) means the catalog is refreshed the moment Sync
  // Data is opened, not only once the enforcer opens the form.
  useVehicleCatalog()

  const setField = key => e => { setForm(f => ({ ...f, [key]: e.target.value })); setFormError('') }

  const toggleVType = id => {
    setFormError('')
    setForm(f => {
      const ids = f.violation_type_ids
      return {
        ...f,
        violation_type_ids: ids.includes(id) ? ids.filter(x => x !== id) : [...ids, id],
      }
    })
  }

  const validateStep = s => {
    if (s === 1) {
      // OVR Number: manual, City-Hall-issued, never auto-generated — same
      // hard requirement as the online IssueOVR wizard (business rule #6).
      // An Enforcer cannot finalize an offline OVR without it either.
      if (!form.ovr_number.trim())  { setFormError('OVR Number is required — copy it exactly from the physical booklet.'); return false }
      if (!form.last_name.trim())  { setFormError('Last name is required.'); return false }
      if (!form.first_name.trim()) { setFormError('First name is required.'); return false }
    }
    if (s === 2) {
      if (!form.plate_number.trim())        { setFormError('Plate number is required.'); return false }
      if (!form.vehicle_type)               { setFormError('Vehicle type is required.'); return false }
      if (form.violation_type_ids.length === 0) { setFormError('Select at least one violation type.'); return false }
    }
    if (s === 3) {
      if (!form.location.trim()) { setFormError('Place of violation is required.'); return false }
    }
    setFormError(''); return true
  }

  const goNext = () => { if (!validateStep(step)) return; setStep(s => s + 1) }
  const goBack = () => { setFormError(''); setStep(s => s - 1) }

  const openForm = () => {
    setForm({ ...EMPTY_FORM, date_issued: manilaNowIso().slice(0, 16) })
    setStep(1); setFormError(''); setShowForm(true)
  }
  const closeForm = () => { setShowForm(false); setFormError(''); setStep(1) }

  const handleSaveOffline = () => {
    if (!validateStep(3)) return
    const selectedVTypes = violationTypes.filter(v => form.violation_type_ids.includes(v.id))
    const totalPenalty   = selectedVTypes.reduce((sum, v) => sum + parseFloat(v.penalty_amount || 0), 0)
    const localId = `offline_${Date.now()}`

    const newReport = {
      ...form,
      // source + ovr_number: identical field names/meaning to what
      // IssueOVR queues (and to the backend's Violation.source /
      // ovr_number). This is what keeps "offline manual form" and
      // "IssueOVR offline" producing ONE consistent Enforcer OVR record
      // shape, both consumed by the same shared sync engine.
      source:               'enforcer_ovr',
      violator_name:       buildViolatorName(form),
      id:                  localId,
      // Idempotency key sent on every sync attempt for this record — see
      // useOfflineQueue.js / backend ViolationCreateView.
      client_offline_id:   localId,
      enforcer:            user?.id,
      enforcer_name:       user?.full_name,
      violation_names:     selectedVTypes.map(v => v.name),
      penalty_amount:      totalPenalty,
      savedAt:             new Date().toISOString(),
      syncStatus:          'queued',
      status:              'pending',
    }
    add(newReport)
    closeForm()
    if (isOnline) setTimeout(handleSync, 400)
  }

  const queued = queuedCount
  const failed = failedCount
  const synced = syncedCount

  const summaryCards = [
    { label: 'Total',  value: reports.length,    color: '#475569', icon: Package },
    { label: 'Queued', value: queued,            color: '#d97706', icon: Clock },
    { label: 'Failed', value: failed,            color: '#dc2626', icon: XCircle },
    { label: 'Synced', value: synced,            color: '#16a34a', icon: CheckCircle2 },
    { label: 'Offline Issuances', value: offlineIssuances, color: '#7c3aed', icon: WifiOff },
  ]

  // ── render ──────────────────────────────────────────────────────────────
  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 14 }}>
      <PageHeader title="Sync Data" />

      {/* Connection Banner */}
      <div className="card card-padded" style={{
        background: isOnline ? 'var(--success-50)' : 'var(--danger-50)',
        border: `1.5px solid ${isOnline ? 'var(--success-100)' : 'var(--danger-100)'}`,
        display: 'flex', alignItems: 'center', gap: 10,
      }}>
        {isOnline
          ? <Wifi size={18} color="var(--success-600)" strokeWidth={2.2} style={{ flexShrink: 0 }} />
          : <WifiOff size={18} color="var(--danger-600)" strokeWidth={2.2} style={{ flexShrink: 0 }} />}
        <div style={{ minWidth: 0, flex: 1 }}>
          <div style={{ fontSize: 13, fontWeight: 700, color: isOnline ? 'var(--success-700)' : 'var(--danger-700)' }}>
            {isOnline ? 'Connected to Internet' : 'No Internet Connection'}
          </div>
          <div className="text-caption" style={{ marginTop: 1 }}>
            {isOnline
              ? queued + failed > 0 ? `${queued + failed} report(s) ready to sync` : "All reports synced. You're up to date."
              : 'Reports saved locally — will auto-sync when connection is restored.'}
          </div>
        </div>
      </div>

      {isOnline && queued + failed > 0 && (
        <Button variant="primary" icon={RefreshCw} onClick={handleSync} disabled={syncing} loading={syncing} fullWidth style={{ background: 'var(--success-600)' }}>
          {syncing ? 'Syncing...' : `Sync ${queued + failed} Report${queued + failed !== 1 ? 's' : ''} Now`}
        </Button>
      )}

      {/* Summary chips */}
      <div style={{ display: 'grid', gridTemplateColumns: isMobile ? 'repeat(3, 1fr)' : 'repeat(5, 1fr)', gap: 8 }}>
        {summaryCards.map(s => {
          const Icon = s.icon
          return (
            <div key={s.label} className="card" style={{ padding: '10px 6px', textAlign: 'center' }}>
              <Icon size={14} color={s.color} style={{ marginBottom: 4 }} />
              <div style={{ fontSize: 16, fontWeight: 700, color: s.color, lineHeight: 1 }}>{s.value}</div>
              <div style={{ fontSize: 9, color: 'var(--slate-500)', fontWeight: 600, textTransform: 'uppercase', marginTop: 3 }}>{s.label}</div>
            </div>
          )
        })}
      </div>

      {!showForm && (
        <Button variant="primary" icon={Plus} onClick={openForm} fullWidth style={{ background: 'var(--warning-500)', color: 'var(--navy-950)' }}>
          Save Offline Report
        </Button>
      )}

      {/* Offline Form */}
      {showForm && (
        <div className="card card-padded" style={{ border: '2px solid var(--warning-500)' }}>
          <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: 20, gap: 12 }}>
            <div>
              <p className="text-title" style={{ fontSize: 15 }}>Save Violation Report Offline</p>
              <p className="text-caption">Saved to your device — auto-submits when back online.</p>
            </div>
            <button onClick={closeForm} className="btn btn-ghost btn-icon" aria-label="Close form" style={{ flexShrink: 0 }}>
              <X size={18} strokeWidth={2} />
            </button>
          </div>

          <StepIndicator step={step} isMobile={isMobile} />

          <div style={{ minHeight: 200 }}>
            {step === 1 && <Step1 form={form} setField={setField} isMobile={isMobile} />}
            {step === 2 && <Step2 form={form} setField={setField} setForm={setForm} toggleVType={toggleVType} violationTypes={violationTypes} />}
            {step === 3 && <Step3 form={form} setField={setField} />}
          </div>

          {formError && <div className="alert alert-danger" style={{ marginTop: 14 }}>{formError}</div>}

          <div style={{ display: 'flex', gap: 10, marginTop: 20, justifyContent: 'space-between', flexWrap: 'wrap' }}>
            <div>
              {step > 1 && <Button variant="secondary" onClick={goBack}>← Back</Button>}
            </div>
            <div style={{ display: 'flex', gap: 10, marginLeft: 'auto' }}>
              <Button variant="secondary" onClick={closeForm}>Cancel</Button>
              {step < 3 ? (
                <Button variant="primary" onClick={goNext} style={{ background: 'var(--warning-500)', color: 'var(--slate-950)' }}>Next →</Button>
              ) : (
                <Button variant="primary" onClick={handleSaveOffline} style={{ background: 'var(--warning-500)', color: 'var(--slate-950)' }}>💾 Save Offline</Button>
              )}
            </div>
          </div>
        </div>
      )}

      {/* Reports on this device that this login may not sync: either saved by
          a different account, or saved before ownership tracking existed
          (owner unknown). Kept (never deleted, never auto-claimed) but NOT
          synced, because syncing them here would file them under the wrong
          enforcer. */}
      {quarantined.length > 0 && (() => {
        const unknownOwner = quarantined.filter(r => r.owner_user_id == null).length
        const otherAccount = quarantined.length - unknownOwner
        return (
          <div className="card" role="status" style={{ padding: '12px 14px', borderLeft: '3px solid var(--warning-500)' }}>
            <div style={{ fontSize: 13, fontWeight: 700, color: 'var(--slate-950)' }}>
              {quarantined.length} offline report{quarantined.length !== 1 ? 's' : ''} on this device cannot be synced from this login
            </div>
            <p className="text-caption" style={{ margin: '4px 0 0' }}>
              {otherAccount > 0 && `${otherAccount} belong${otherAccount === 1 ? 's' : ''} to another account and will sync when that account signs in on this device. `}
              {unknownOwner > 0 && `${unknownOwner} ${unknownOwner === 1 ? 'was' : 'were'} saved before owner tracking and will not be synced automatically. `}
              They stay saved on this device.
            </p>
          </div>
        )
      })()}

      {/* Offline reports list */}
      <div>
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: 8 }}>
          <p className="text-caption" style={{ margin: 0 }}>
            <strong style={{ color: 'var(--slate-950)' }}>{reports.length}</strong> offline report{reports.length !== 1 ? 's' : ''} on this device
          </p>
        </div>

        {reports.length === 0 ? (
          <div className="card">
            <EmptyState title="No offline reports saved" message='Tap "Save Offline Report" to save a report without internet.' />
          </div>
        ) : (
          <div style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
            {reports.map(r => <OfflineCard key={r.id} r={r} onRetry={handleRetry} />)}
          </div>
        )}
      </div>

      {lastSyncResult && (
        <div className="text-caption" style={{ textAlign: 'center' }}>
          Last sync: {lastSyncResult.at.toLocaleString('en-PH')}
          {' — '}
          {lastSyncResult.succeeded} synced{lastSyncResult.failed > 0 ? `, ${lastSyncResult.failed} failed` : ''}
        </div>
      )}
    </div>
  )
}