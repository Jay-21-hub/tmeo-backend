function Step2({ form, setField, setForm, toggleVType, violationTypes }) {
  const selected = violationTypes.filter(v => form.violation_type_ids.includes(v.id))
  const total = selected.reduce((s, v) => s + parseFloat(v.penalty_amount || 0), 0)

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 14 }}>
      <Field label="Plate Number" required>
        {(id) => <TextInput id={id} placeholder="e.g. ABC 1234" value={form.plate_number} onChange={setField('plate_number')} />}
      </Field>
      <VehicleCatalogField
        value={{ vehicle_type: form.vehicle_type, vehicle_brand: form.vehicle_brand, vehicle_model: form.vehicle_model }}
        onSelect={v => setForm(f => ({ ...f, ...v }))}
        onClear={() => setForm(f => ({ ...f, vehicle_type: '', vehicle_brand: '', vehicle_model: '' }))}
        required
        accent="var(--warning-600)"
        accentLight="var(--warning-50)"
      />
      <div>
        <label className="field-label" style={{ marginBottom: 8 }}>
          Violation Types <span className="field-required" aria-hidden="true">*</span>
          <span style={{ fontWeight: 400, color: 'var(--slate-500)', marginLeft: 6, textTransform: 'none', letterSpacing: 0 }}>
            ({form.violation_type_ids.length} selected)
          </span>
        </label>
        {violationTypes.length > 0 ? (
          <div style={{ border: '1px solid var(--color-border)', borderRadius: 'var(--radius-md)', maxHeight: 220, overflowY: 'auto', background: 'var(--white)' }}>
            {violationTypes.map(v => {
              const checked = form.violation_type_ids.includes(v.id)
              return (
                <label key={v.id} style={{
                  display: 'flex', alignItems: 'center', gap: 10,
                  padding: '9px 14px', cursor: 'pointer',
                  borderBottom: '1px solid var(--slate-100)',
                  background: checked ? 'var(--blue-50)' : 'var(--white)',
                }}>
                  <input type="checkbox" checked={checked} onChange={() => toggleVType(v.id)}
                    style={{ accentColor: 'var(--blue-600)', width: 15, height: 15, cursor: 'pointer', flexShrink: 0 }} />
                  <div style={{ flex: 1, minWidth: 0 }}>
                    <div style={{ fontSize: 13, fontWeight: checked ? 700 : 500, color: 'var(--slate-950)' }}>{v.name}</div>
                    <div className="text-caption">{v.code} · ₱{parseFloat(v.penalty_amount).toLocaleString('en-PH', { minimumFractionDigits: 2 })}</div>
                  </div>
                  {checked && <Check size={14} color="var(--blue-600)" strokeWidth={3} style={{ flexShrink: 0 }} />}
                </label>
              )
            })}
          </div>
        ) : (
          <div className="alert alert-warning">⚠ These options have not been cached on this device yet. Connect to the internet once to load the latest options.</div>
        )}
        {selected.length > 0 && (
          <div style={{ marginTop: 8, padding: '10px 14px', background: 'var(--blue-50)', borderRadius: 'var(--radius-md)', border: '1px solid var(--blue-100)' }}>
            <div className="text-label" style={{ marginBottom: 4 }}>Selected Violations</div>
            <div style={{ display: 'flex', flexWrap: 'wrap', gap: 4, marginBottom: 6 }}>
              {selected.map(v => <Badge key={v.id} tone="info" dot={false}>{v.name}</Badge>)}
            </div>
            <div style={{ fontSize: 13, fontWeight: 700, color: 'var(--navy-700)' }}>
              Total Penalty: ₱{total.toLocaleString('en-PH', { minimumFractionDigits: 2 })}
            </div>
          </div>
        )}
      </div>
    </div>
  )
}

