const VTYPES_KEY  = 'tmeo_cached_violation_types'

function getCachedVTypes() {
  try { return JSON.parse(localStorage.getItem(VTYPES_KEY) || '[]') } catch { return [] }
}
function cacheVTypes(t) { localStorage.setItem(VTYPES_KEY, JSON.stringify(t)) }

// Wording matches Requirement #10 section 8's required offline-status
// labels exactly.
const STATUS_STYLE = {
  queued:  { tone: 'warning', label: '⏳ Pending Sync' },
  syncing: { tone: 'info',    label: '🔄 Syncing…'     },
  synced:  { tone: 'success', label: '✓ Synced'        },
  failed:  { tone: 'danger',  label: '⚠️ Sync Failed'   },
}

const STEPS = [
  { id: 1, label: 'Violator Info',        icon: User },
  { id: 2, label: 'Vehicle & Violations', icon: Car },
  { id: 3, label: 'Incident Details',     icon: MapPin },
]

const EMPTY_FORM = {
  ovr_number: '',
  last_name: '', first_name: '', middle_initial: '',
  address: '', license_number: '',
  plate_number: '', vehicle_type: '', vehicle_brand: '', vehicle_model: '',
  violation_type_ids: [],
  location: '', remarks: '',
  date_issued: manilaNowIso().slice(0, 16),
}

function buildViolatorName(form) {
  const ln = form.last_name.trim()
  const fn = form.first_name.trim()
  const mi = form.middle_initial.trim()
  if (!ln && !fn) return ''
  let name = `${ln}, ${fn}`
  if (mi) name += ` ${mi.replace(/\.+$/, '')}.`
  return name
}

// ─── Step Indicator (module-level — prevent recreation on every render) ───
function StepIndicator({ step, isMobile }) {
  return (
    <div style={{ display: 'flex', alignItems: 'center', marginBottom: 24 }}>
      {STEPS.map((s, i) => {
        const done = step > s.id, active = step === s.id
        const Icon = s.icon
        return (
          <div key={s.id} style={{ display: 'flex', alignItems: 'center', flex: i < STEPS.length - 1 ? 1 : 'none' }}>
            <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', gap: 4 }}>
              <div style={{
                width: 36, height: 36, borderRadius: '50%', display: 'flex',
                alignItems: 'center', justifyContent: 'center',
                background: done ? 'var(--success-600)' : active ? 'var(--warning-500)' : 'var(--slate-100)',
                border: active ? '2px solid var(--warning-600)' : done ? '2px solid var(--success-700)' : '2px solid var(--color-border)',
                color: done || active ? '#fff' : 'var(--slate-500)', flexShrink: 0,
              }}>
                {done ? <Check size={16} strokeWidth={2.5} /> : <Icon size={16} strokeWidth={2.2} />}
              </div>
              {!isMobile && (
                <div style={{ fontSize: 10, fontWeight: 700, whiteSpace: 'nowrap', color: done ? 'var(--success-600)' : active ? 'var(--warning-700)' : 'var(--slate-500)' }}>
                  {s.label}
                </div>
              )}
            </div>
            {i < STEPS.length - 1 && (
              <div style={{ flex: 1, height: 2, margin: isMobile ? '0 6px' : '-16px 8px 0', borderRadius: 2, background: done ? 'var(--success-600)' : 'var(--color-border)' }} />
            )}
          </div>
        )
      })}
    </div>
  )
}

